-- EJECUTA ESTO EN UN WORKSHEET DE TU PROPIA CUENTA TRIAL DE SNOWFLAKE.
-- Requiere un rol con privilegios CREATE DATABASE y CREATE WAREHOUSE.
-- En una cuenta trial personal, normalmente puedes usar ACCOUNTADMIN.
USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS RIDERS_LAB_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS RIDERS_LAB_DB;
CREATE SCHEMA IF NOT EXISTS RIDERS_LAB_DB.PUZZLE;

USE WAREHOUSE RIDERS_LAB_WH;
USE DATABASE RIDERS_LAB_DB;
USE SCHEMA PUZZLE;

SELECT CURRENT_ROLE() AS ROLE_ACTIVO,
       CURRENT_DATABASE() AS BASE_ACTIVA,
       CURRENT_SCHEMA() AS ESQUEMA_ACTIVO,
       CURRENT_WAREHOUSE() AS WAREHOUSE_ACTIVO;
